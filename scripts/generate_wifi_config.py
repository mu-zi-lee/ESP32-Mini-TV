"""Generate an ignored PlatformIO header from the local .env file."""

from pathlib import Path
import os

Import("env")


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
            value = value[1:-1]
        values[key] = value
    return values


def c_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n")


project_dir = Path(env["PROJECT_DIR"])
env_values = read_env(project_dir / ".env")
ssid = env_values.get("MINITV_WIFI_SSID", os.environ.get("MINITV_WIFI_SSID", ""))
wifiPassword = env_values.get("MINITV_WIFI_PASSWORD", os.environ.get("MINITV_WIFI_PASSWORD", ""))
header = (
    "// Generated by scripts/generate_wifi_config.py; do not edit or commit.\n"
    "#pragma once\n\n"
    f'#define MINITV_WIFI_SSID "{c_string(ssid)}"\n'
    f'#define MINITV_WIFI_PASSWORD "{c_string(wifiPassword)}"\n'
)

output = project_dir / "include" / "wifi_config.h"
output.parent.mkdir(parents=True, exist_ok=True)
if not output.exists() or output.read_text(encoding="utf-8") != header:
    output.write_text(header, encoding="utf-8")
print("Wi-Fi build config: {}".format("configured" if ssid else "empty (use setup API)"))
