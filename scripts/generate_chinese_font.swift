for character in characters {
  var pixels = [UInt8](repeating: 0, count: size * size)
  let colorSpace = CGColorSpaceCreateDeviceGray()
  guard let context = CGContext(data: &pixels, width: size, height: size, bitsPerComponent: 8, bytesPerRow: size, space: colorSpace, bitmapInfo: CGImageAlphaInfo.none.rawValue) else { continue }
  context.translateBy(x: 0, y: CGFloat(size))
  context.scaleBy(x: 1, y: -1)
  let attributed = NSAttributedString(string: String(character), attributes: [
    kCTFontAttributeName as NSAttributedString.Key: font,
    kCTForegroundColorAttributeName as NSAttributedString.Key: CGColor(gray: 1, alpha: 1),
  ])
  let line = CTLineCreateWithAttributedString(attributed)
  let bounds = CTLineGetBoundsWithOptions(line, [])
  let drawX = (CGFloat(size) - bounds.width) / 2 - bounds.origin.x
  let drawY = (CGFloat(size) - bounds.height) / 2 - bounds.origin.y
  context.textPosition = CGPoint(x: drawX, y: drawY)
  CTLineDraw(line, context)
  var bytes = [String]()
  for row in 0..<size {
    var value: UInt8 = 0
    for column in 0..<8 where pixels[row * size + column] > 64 {
